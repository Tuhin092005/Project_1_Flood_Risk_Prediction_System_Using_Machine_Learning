# Function for flood prediction

def predict_flood_risk(input_data):

    input_df = pd.DataFrame(
        [input_data],
        columns=X.columns
    )

    input_scaled = scaler.transform(input_df)

    prediction = rf_model.predict(input_scaled)

    return prediction[0]

